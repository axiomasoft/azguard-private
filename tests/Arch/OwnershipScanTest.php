it('has an owner for every production file and no row for a file that is nowhere', function (): void {
    $root = dirname(__DIR__, 2).'/';
    $ownership = Ownership::fromOracle();
    $unowned = array_values(array_filter(
        array_map(static fn (string $file): string => str_replace($root, '', $file), SourceScan::files()),
        static fn (string $path): bool => $ownership->fileOwner($path) === null,
    ));
    $gone = [];

    foreach ($ownership->rows() as $row) {
        // A `new` row names a file that does not exist yet; a `retire` row names one that P2 has deleted (D16).
        if (in_array($row['action'] ?? null, ['new', 'retire'], true)) {
            continue;
        }
        $moved = isset($row['target_path']) && is_file($root.explode(' + ', $row['target_path'])[0]);
        // D17: a type P2 renames to a module FQCN lives where the core PSR-4 root puts that FQCN until P3 moves it.
        $target = explode(' + ', (string) ($row['target'] ?? ''))[0];
        $interim = str_starts_with($target, 'AzGuard\\')
            && is_file($root.'packages/core/src/'.str_replace('\\', '/', substr($target, strlen('AzGuard\\'))).'.php');

        if (! is_file($root.$row['current_path']) && ! $moved && ! $interim) {
            $gone[] = $row['current_path'];
        }
    }

    expect($unowned)->toBe([], 'a production file has no row in the oracle; regenerate it with target_map.py')
        ->and($gone)->toBe([], 'a row of the oracle names a file that exists neither at its current nor at its target path');
});

