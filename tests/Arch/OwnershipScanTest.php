/*
 * I2 and I3 (PLAN1 P1.4), report mode until P3 exit: the current violations must equal tests/Arch/Allowlists/i2.json and
 * i3.json exactly. A new violation fails now; a listed one that no longer occurs is stale and fails too, so the lists only
 * shrink, and every entry names the phase that removes it. At P3 exit the lists are empty and the scans block as they are.
 *
 * The owner of a file is the owner of the oracle row whose `current_path` (`target_path` once moved) is that file; a
 * reference resolves to a row by FQCN. Oracle: tests/Arch/Fixtures/target-map.json, a byte copy of the plan artifact
 * generated by `target_map.py` (D14), never edited by hand.
 */

/** @param list<array<string, mixed>> $rows */
function ownershipRow(string $owner, string $fqcn, string $path, string $phase = 'P3'): array
{
    return ['current' => $fqcn, 'current_path' => $path, 'target' => $fqcn, 'target_path' => $path, 'owner' => $owner, 'action' => 'move', 'phase' => $phase];
}

/**
 * Writes the files into a throw-away repository tree, scans them against a synthetic oracle and removes the tree.
 *
 * @param  array<string, string>  $sources  path relative to the root => code
 * @param  list<array<string, mixed>>  $rows
 * @return list<array{file: string, reference: string, kind: string, invariant: string, owner_phase: string|null}>
 */
function ownershipScanOf(array $sources, array $rows): array
{
    $root = sys_get_temp_dir().'/azguard-ownership-'.bin2hex(random_bytes(4));
    $files = [];

    try {
        foreach ($sources as $path => $code) {
            is_dir(dirname($root.'/'.$path)) || mkdir(dirname($root.'/'.$path), 0777, true);
            file_put_contents($root.'/'.$path, $code);
            $files[] = $root.'/'.$path;
        }

        return BoundaryScan::violations(Ownership::of($rows), $files, $root);
    } finally {
        foreach ($files as $file) {
            unlink($file);
        }
        $directories = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($root, FilesystemIterator::SKIP_DOTS), RecursiveIteratorIterator::CHILD_FIRST);

        foreach ($directories as $directory) {
            rmdir($directory->getPathname());
        }
        rmdir($root);
    }
}

